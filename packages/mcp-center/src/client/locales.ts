/** Translate product-owned copy while retaining user names and original provider diagnostics. */
export function mcpText(value: string, zh: boolean): string {
  if (zh) return value
  const count = /^协议握手成功，发现 (\d+) 个工具；未执行工具调用，具体操作权限尚待核验。$/u.exec(value)
  if (count) return `Protocol handshake succeeded; discovered ${count[1]} tools. No tools were called and operation permissions remain unverified.`
  return EN[value] ?? value
}
